#!/usr/bin/env python3
"""Generate docs/coverage.md from the controls, the spec and the expectations.

The inventory is a claim about the project (how many controls are reviewed,
how many have a fixture expectation, which ones have none), so it is a file
in the repo rather than a paragraph that drifts. `ci/checks.sh` runs
`ci/coverage.py --check` and fails when the committed file is stale; run
`python3 ci/coverage.py` to regenerate after adding or changing a control or
an expectation.
"""
import glob
import re
import sys

import yaml

OUT = "docs/coverage.md"
CHECK = "--check" in sys.argv[1:]


def blocks():
    out = {}
    for f in sorted(glob.glob("controls/*.pp")):
        t = open(f).read()
        for m in re.finditer(r'^control "([^"]+)" \{\n', t, re.M):
            end = t.index("\n}\n", m.start())
            out[m.group(1)] = (f, t[m.start():end])
    return out


def tag(block, key):
    m = re.search(r'\b%s\s*=\s*"([^"]*)"' % re.escape(key), block)
    return m.group(1) if m else ""


def title(block):
    m = re.search(r'^\s+title\s*=\s*"([^"]*)"', block, re.M)
    return m.group(1) if m else ""


def cols(text):
    """The fixtures block of a spec record: host -> statuses."""
    m = re.search(r"\n    fixtures:\n((?:      [a-z][a-z-]*: \[[^\]]*\]\n)+)", text)
    return len(re.findall(r"^      [a-z][a-z-]*: ", m.group(1), re.M)) if m else 0


spec = yaml.safe_load(open("spec/controls.yaml"))
core = {r["control"]: r for r in spec["controls"]}
hosts = len(spec["fixtures"]["hosts"])
reg = {}
if glob.glob("test/expectations.yaml"):
    doc = yaml.safe_load(open("test/expectations.yaml"))
    for c in doc.get("checks") or []:
        reg.setdefault(c["control"], []).append(c)

bs = blocks()
rows = []
for name in sorted(bs, key=lambda n: (tag(bs[n][1], "agentreach"), n)):
    f, b = bs[name]
    cid = tag(b, "agentreach")
    cls = tag(b, "agentreach_class")
    exp = []
    if name in core:
        n = len(core[name].get("fixtures") or {})
        exp.append("spec (%d hosts)" % n)
    for c in reg.get(name, []):
        vars = c.get("vars") or {}
        label = "regression"
        if vars:
            label += " (" + ", ".join("%s=%s" % (k, vars[k]) for k in sorted(vars)) + ")"
        exp.append("%s, %d hosts" % (label, len(c.get("fixtures") or {})))
    rows.append((cid, name, title(b), cls, "; ".join(exp) or "—"))

mapped = sum(1 for n in bs if tag(bs[n][1], "agentreach_class") == "mapped")
ext = sum(1 for n in bs if tag(bs[n][1], "agentreach_class") == "agentreach_extension")
nv = len(bs) - len(core)
covered = sum(1 for r in rows if r[4] != "—")

lines = [
    "# Control coverage",
    "",
    "Generated by `python3 ci/coverage.py`; `ci/checks.sh` fails when this",
    "file is stale. Regenerate after adding or changing a control or an",
    "expectation.",
    "",
    "- %d controls: %d core (spec/controls.yaml), %d needs_validation"
    % (len(bs), len(core), nv),
    "- %d mapped to an AISVS id, %d AgentReach extensions" % (mapped, ext),
    "- %d controls have a fixture expectation (a spec record or a"
    " regression check); %d have none" % (covered, len(bs) - covered),
    "- %d fixture hosts" % hosts,
    "",
    "| Id | Control | Class | Expectations |",
    "|----|---------|-------|--------------|",
]
for cid, name, ttl, cls, exp in rows:
    lines.append("| %s | %s | %s | %s |" % (cid, ttl, cls, exp))
text = "\n".join(lines) + "\n"

if CHECK:
    try:
        old = open(OUT).read()
    except OSError:
        old = ""
    if old != text:
        print("%s is stale; run: python3 ci/coverage.py" % OUT)
        sys.exit(1)
    print("%s is current (%d controls, %d with expectations)" % (OUT, len(bs), covered))
else:
    open(OUT, "w").write(text)
    print("wrote %s (%d controls, %d with expectations)" % (OUT, len(bs), covered))
